import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const consentDir = join(projectRoot, 'src', 'consent');
const outputFile = join(consentDir, 'consent-policy.documents.generated.ts');

const documents = [
  ['PRIVACY_NOTICE_TH', 'privacy-notice.th.md'],
  ['PRIVACY_NOTICE_EN', 'privacy-notice.en.md'],
  ['TERMS_OF_SERVICE_TH', 'terms-of-service.th.md'],
  ['TERMS_OF_SERVICE_EN', 'terms-of-service.en.md'],
];

const output = [
  '// This file is generated by scripts/generate-consent-documents.mjs.',
  '// Edit the Markdown source files, then run npm run generate:consent-documents.',
  '',
  ...documents.flatMap(([exportName, fileName]) => {
    const content = readFileSync(join(consentDir, fileName), 'utf8');
    return [`export const ${exportName} = ${JSON.stringify(content)};`, ''];
  }),
].join('\n');

writeFileSync(outputFile, output, 'utf8');
