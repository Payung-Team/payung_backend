--
--   คอลัมน์นี้แยกสองกรณีออกจากกัน เพื่อให้การ์ดผู้รับบริการแสดงป้ายได้ถูกต้อง
--   (ก่อนหน้านี้ป้าย "ข้อมูลจากเจ้าตัว" ใน FE เป็นข้อความ hardcode ไม่ผูกกับข้อมูลจริง)
